# ==========================================

# 6. Variables

# ==========================================

# A variable is a name given to a memory location.

name = "Sundram"
age = 25

print("My name is", name)
print("My age is", age)

# ==========================================

# 7. Data Types

# ==========================================

student_name = "Rahul"      # String
student_age = 18            # Integer
student_marks = 89.5        # Float
is_student = True           # Boolean
address = None              # NoneType

print(student_name)
print(student_age)
print(student_marks)
print(is_student)
print(address)

# ==========================================

# 8. Checking Data Types

# ==========================================

print(type(student_name))
print(type(student_age))
print(type(student_marks))
print(type(is_student))
print(type(address))

# ==========================================

# 9. Dynamic Typing

# ==========================================

# Python automatically identifies data types.

value = 10
print(type(value))

value = "Hello"
print(type(value))

# Same variable can store different types of values.

